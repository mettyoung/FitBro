package com.mettyoung.fitbro.data.health

import androidx.health.connect.client.records.ExerciseSessionRecord as E
import com.mettyoung.fitbro.data.model.WorkoutType

/** FR-3: Health Connect exercise type → shared [WorkoutType]. See tasks/workout-type-mapping.md. */
internal fun exerciseTypeToWorkoutType(type: Int): WorkoutType = when (type) {
    E.EXERCISE_TYPE_RUNNING, E.EXERCISE_TYPE_RUNNING_TREADMILL -> WorkoutType.RUNNING
    E.EXERCISE_TYPE_WALKING -> WorkoutType.WALKING
    E.EXERCISE_TYPE_HIKING, E.EXERCISE_TYPE_SNOWSHOEING -> WorkoutType.HIKING
    E.EXERCISE_TYPE_BIKING, E.EXERCISE_TYPE_BIKING_STATIONARY -> WorkoutType.CYCLING
    E.EXERCISE_TYPE_SWIMMING_POOL, E.EXERCISE_TYPE_SWIMMING_OPEN_WATER -> WorkoutType.SWIMMING
    E.EXERCISE_TYPE_ELLIPTICAL -> WorkoutType.ELLIPTICAL
    E.EXERCISE_TYPE_ROWING, E.EXERCISE_TYPE_ROWING_MACHINE -> WorkoutType.ROWING
    E.EXERCISE_TYPE_STAIR_CLIMBING, E.EXERCISE_TYPE_STAIR_CLIMBING_MACHINE -> WorkoutType.STAIR_CLIMBING
    E.EXERCISE_TYPE_HIGH_INTENSITY_INTERVAL_TRAINING -> WorkoutType.HIIT
    E.EXERCISE_TYPE_DANCING -> WorkoutType.DANCE
    E.EXERCISE_TYPE_BOOT_CAMP, E.EXERCISE_TYPE_EXERCISE_CLASS -> WorkoutType.CROSS_TRAINING
    E.EXERCISE_TYPE_WHEELCHAIR -> WorkoutType.WHEELCHAIR
    E.EXERCISE_TYPE_PADDLING -> WorkoutType.PADDLING
    E.EXERCISE_TYPE_SKIING -> WorkoutType.SKIING
    E.EXERCISE_TYPE_SNOWBOARDING -> WorkoutType.SNOWBOARDING
    E.EXERCISE_TYPE_SKATING, E.EXERCISE_TYPE_ICE_SKATING -> WorkoutType.SKATING

    E.EXERCISE_TYPE_STRENGTH_TRAINING -> WorkoutType.STRENGTH_TRAINING
    E.EXERCISE_TYPE_WEIGHTLIFTING -> WorkoutType.WEIGHTLIFTING
    E.EXERCISE_TYPE_CALISTHENICS -> WorkoutType.CALISTHENICS
    E.EXERCISE_TYPE_GYMNASTICS -> WorkoutType.GYMNASTICS

    E.EXERCISE_TYPE_YOGA -> WorkoutType.YOGA
    E.EXERCISE_TYPE_PILATES -> WorkoutType.PILATES
    E.EXERCISE_TYPE_STRETCHING -> WorkoutType.STRETCHING
    E.EXERCISE_TYPE_GUIDED_BREATHING -> WorkoutType.MINDFULNESS

    E.EXERCISE_TYPE_BADMINTON -> WorkoutType.BADMINTON
    E.EXERCISE_TYPE_TENNIS -> WorkoutType.TENNIS
    E.EXERCISE_TYPE_TABLE_TENNIS -> WorkoutType.TABLE_TENNIS
    E.EXERCISE_TYPE_SQUASH -> WorkoutType.SQUASH
    E.EXERCISE_TYPE_RACQUETBALL -> WorkoutType.RACQUETBALL
    E.EXERCISE_TYPE_BASKETBALL -> WorkoutType.BASKETBALL
    E.EXERCISE_TYPE_SOCCER -> WorkoutType.SOCCER
    E.EXERCISE_TYPE_VOLLEYBALL -> WorkoutType.VOLLEYBALL
    E.EXERCISE_TYPE_BASEBALL, E.EXERCISE_TYPE_SOFTBALL -> WorkoutType.BASEBALL_SOFTBALL
    E.EXERCISE_TYPE_CRICKET -> WorkoutType.CRICKET
    E.EXERCISE_TYPE_RUGBY -> WorkoutType.RUGBY
    E.EXERCISE_TYPE_FOOTBALL_AMERICAN -> WorkoutType.AMERICAN_FOOTBALL
    E.EXERCISE_TYPE_FOOTBALL_AUSTRALIAN -> WorkoutType.AUSTRALIAN_FOOTBALL
    E.EXERCISE_TYPE_HANDBALL -> WorkoutType.HANDBALL
    E.EXERCISE_TYPE_ICE_HOCKEY, E.EXERCISE_TYPE_ROLLER_HOCKEY -> WorkoutType.HOCKEY
    E.EXERCISE_TYPE_WATER_POLO -> WorkoutType.WATER_POLO
    E.EXERCISE_TYPE_FRISBEE_DISC -> WorkoutType.DISC_SPORTS
    E.EXERCISE_TYPE_BOXING -> WorkoutType.BOXING
    E.EXERCISE_TYPE_MARTIAL_ARTS, E.EXERCISE_TYPE_FENCING -> WorkoutType.MARTIAL_ARTS
    E.EXERCISE_TYPE_ROCK_CLIMBING -> WorkoutType.CLIMBING
    E.EXERCISE_TYPE_GOLF -> WorkoutType.GOLF
    E.EXERCISE_TYPE_SURFING -> WorkoutType.SURFING

    // OTHER_WORKOUT, SAILING, SCUBA_DIVING, PARAGLIDING and any future/unknown code.
    else -> WorkoutType.OTHER
}
